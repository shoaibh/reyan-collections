export const INDIAN_STATES: ReadonlyArray<{ name: string; code: string }> = STATES.map(
  ([code, name]) => ({ name, code }),
).sort((a, b) => a.name.localeCompare(b.name))

export function stateCodeFor(name: string): string | null {
  return INDIAN_STATES.find((s) => s.name === name)?.code ?? null
}

export function normalizePhone(raw: string): string | null {
  let digits = raw.replace(/\D/g, '')
  if (digits.length === 12 && digits.startsWith('91')) digits = digits.slice(2)
  else if (digits.length === 11 && digits.startsWith('0')) digits = digits.slice(1)
  return /^[6-9][0-9]{9}$/.test(digits) ? digits : null
}

export const PINCODE_RE = /^[0-9]{6}$/

export function maskPhone(phone: string): string {
  return `••••••${phone.slice(-4)}`
}
